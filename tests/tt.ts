// ============================================================================
// tests/tt.ts — 测试时间预算单一来源（慢内核/模拟器环境缩放）
// ----------------------------------------------------------------------------
// 背景（v0.5.25.1 慢内核适配批，iSH 实弹驱动）：端到端用例真实 spawn 解释器
// 跑完整监督回路，单轮在普通机器 3–14s、在慢速内核（iOS 模拟器 / iSH 类
// 沙箱）上可达 2–7 分钟。断言标准一字不动 —— 本模块只放大**等待上限**
// （B-15 纪律：放宽的是等待上限，不是断言标准）。
//
// 用法：把逐例超时 `}, 120_000);` 换成 `}, TT);`；性能护栏用 PERF(ms) 包裹。
// 缩放：ORG_TEST_TIMEOUT_SCALE=6（iSH/模拟器建议值）；默认 1 = 与历史完全一致。
// ============================================================================

/** 环境缩放系数（默认 1；>0 的有限数才生效，否则回落 1）。 */
export const TEST_TIME_SCALE = (() => {
  const n = Number(process.env.ORG_TEST_TIMEOUT_SCALE ?? "1");
  return Number.isFinite(n) && n > 0 ? n : 1;
})();

/** 默认逐例超时（历史值 120s × 缩放）。 */
export const TT = Math.round(120_000 * TEST_TIME_SCALE);

/** 性能护栏缩放（如「24 音渲染 < 10s」的安静环境护栏在慢内核上按比例放大）。 */
export const PERF = (ms: number): number => Math.round(ms * TEST_TIME_SCALE);
